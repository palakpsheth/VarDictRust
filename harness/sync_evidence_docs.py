#!/usr/bin/env python3
"""harness/sync_evidence_docs.py

Automated synchronizer for release evidence fingerprints and SHA-256 manifests.
Reads the live engine fingerprints and on-disk `benchmarks/evidence/*.json` files
generated by live validation runners (`harness/recertify.sh`) and updates the
documentation surfaces (`omnibus-empirical-validation.md`, `DIVERGENCES.md`,
`test-matrix-and-ci-audit.md`, `benchmarks/README.md`, and the active
`docs/release/vX.Y.Z-pr.md` file).

Adheres strictly to AGENTS.md §0b (never modifies `benchmarks/evidence/*.json`)
and `test_stdlib_purity.py` (100% Python standard library).
"""

import argparse
import hashlib
import json
import pathlib
import re
import sys


def sync_docs(repo_root: pathlib.Path, check: bool = False) -> int:
    ev_dir = repo_root / "benchmarks" / "evidence"
    json_files = sorted(ev_dir.glob("*.json"))
    if len(json_files) != 16:
        print(
            f"ERROR: expected 16 evidence JSON files in {ev_dir}, found {len(json_files)}",
            file=sys.stderr,
        )
        return 1

    hg008_data = json.loads((ev_dir / "hg008-tier2.json").read_text(encoding="utf-8"))
    fp = hg008_data.get("fingerprint", "")
    scale_data = json.loads((ev_dir / "scale.json").read_text(encoding="utf-8"))
    scale_extra = scale_data.get("extra", {})
    perf_fp = scale_extra.get("perf_fingerprint", "")
    if not re.match(r"^[0-9a-f]{16}$", fp) or not re.match(r"^[0-9a-f]{16}$", perf_fp):
        print(
            f"ERROR: invalid fingerprint ({fp!r}) or perf_fingerprint ({perf_fp!r})",
            file=sys.stderr,
        )
        return 1

    s8 = float(scale_extra.get("speedup_8", scale_extra.get("s8", 0.0)))
    rss_ratio = float(
        scale_extra.get("rss_ratio_chr1_vs_10mb", scale_extra.get("rss_ratio", 0.0))
    )
    rss_kb_map = scale_extra.get("maxrss_kb", scale_extra.get("rss_kb", {}))
    chr1_rss_kb = rss_kb_map.get("248956422", rss_kb_map.get("249250621", 0))
    chr1_rss_gib = float(chr1_rss_kb) / (1024.0 * 1024.0)
    span10_rss_gib = float(rss_kb_map.get("10000000", 0)) / (1024.0 * 1024.0)
    wall_s_map = scale_extra.get("wall_s", {})
    th1_s = float(wall_s_map.get("1", 0.0))
    th8_s = float(wall_s_map.get("8", 0.0))

    mismatches = []
    pattern_errors: list[str] = []

    def sub_required(
        pattern: str, repl: str, text: str, label: str, flags: int = 0
    ) -> str:
        new_text, count = re.subn(pattern, repl, text, flags=flags)
        if count == 0:
            pattern_errors.append(
                f"ERROR: required pattern not found in {label}: {pattern!r}"
            )
        return new_text

    # 1. Update docs/validation/omnibus-empirical-validation.md
    omnibus_path = repo_root / "docs" / "validation" / "omnibus-empirical-validation.md"
    # The omnibus §13 SHA-256 table is a required surface: every evidence JSON
    # must have exactly one row. A deleted or reformatted row must fail loudly
    # instead of passing silently via an unmatched substitution.
    required_docs = [
        omnibus_path,
        repo_root / "DIVERGENCES.md",
        repo_root / "docs" / "testing" / "test-matrix-and-ci-audit.md",
        repo_root / "benchmarks" / "README.md",
        repo_root
        / ".agents"
        / "skills"
        / "vardictrust-release"
        / "references"
        / "version-surface-map.md",
    ]
    for req in required_docs:
        if not req.is_file():
            print(
                f"ERROR: required documentation surface missing: {req.relative_to(repo_root)}",
                file=sys.stderr,
            )
            return 1
    sha_rows_verified = 0
    if omnibus_path.is_file():  # guaranteed present by required_docs check above
        orig_text = omnibus_path.read_text(encoding="utf-8")
        text = sub_required(
            r"(\*\*Certified Release Engine Fingerprint:\*\*\s*`)[0-9a-f]{16}(`)",
            rf"\g<1>{fp}\2",
            orig_text,
            "docs/validation/omnibus-empirical-validation.md",
        )
        sha_rows_verified = 0
        for jf in json_files:
            jf_data = json.loads(jf.read_text(encoding="utf-8"))
            jf_fp = jf_data.get("fingerprint", fp)
            jf_sha = hashlib.sha256(jf.read_bytes()).hexdigest()
            fname_esc = re.escape(jf.name)
            text, n = re.subn(
                rf"(\|\s*\[`{fname_esc}`\]\([^)]+\)\s*\|\s*`)[0-9a-f]{{16}}(`\s*\|\s*`)[0-9a-f]{{64}}(`\s*\|)",
                rf"\g<1>{jf_fp}\g<2>{jf_sha}\3",
                text,
            )
            if n != 1:
                have = "missing" if n == 0 else f"duplicated ({n} matches)"
                print(
                    f"ERROR: omnibus SHA-256 table row for {jf.name} is {have}; "
                    "expected exactly one row per evidence JSON.",
                    file=sys.stderr,
                )
                return 1
            sha_rows_verified += n
        if sha_rows_verified != len(json_files):
            print(
                f"ERROR: omnibus SHA-256 table has {sha_rows_verified} matching rows, "
                f"expected one per evidence JSON ({len(json_files)}); a manifest row "
                "may have been deleted or reformatted.",
                file=sys.stderr,
            )
            return 1
        if text != orig_text:
            if check:
                mismatches.append(str(omnibus_path.relative_to(repo_root)))
            else:
                omnibus_path.write_text(text, encoding="utf-8")

    # 2. Update DIVERGENCES.md
    div_path = repo_root / "DIVERGENCES.md"
    if div_path.is_file():
        orig_text = div_path.read_text(encoding="utf-8")
        text = sub_required(
            r"(under release engine fingerprint `)[0-9a-f]{16}(`)",
            rf"\g<1>{fp}\2",
            orig_text,
            "DIVERGENCES.md",
        )
        text = sub_required(
            r"([0-9]+\.[0-9]+ GiB peak RSS across the full 249 Mbp chromosome in the 3-run median certified series[^)]*)",
            f"{chr1_rss_gib:.2f} GiB peak RSS across the full 249 Mbp chromosome in the 3-run median certified series, {rss_ratio:.2f}× flat RSS ratio vs 10 Mbp",
            text,
            "DIVERGENCES.md",
        )
        text = sub_required(
            r"(Scaling Budget:\s+PASS \()[0-9]+\.[0-9]+x speedup, [0-9]+\.[0-9]+x flat RSS",
            rf"\g<1>{s8:.2f}x speedup, {rss_ratio:.2f}x flat RSS",
            text,
            "DIVERGENCES.md",
        )
        if text != orig_text:
            if check:
                mismatches.append(str(div_path.relative_to(repo_root)))
            else:
                div_path.write_text(text, encoding="utf-8")

    # 3. Update docs/testing/test-matrix-and-ci-audit.md
    matrix_path = repo_root / "docs" / "testing" / "test-matrix-and-ci-audit.md"
    if matrix_path.is_file():
        orig_text = matrix_path.read_text(encoding="utf-8")
        text = sub_required(
            r"(\*\*Certified Release Engine Fingerprint:\*\*\s*`)[0-9a-f]{16}(`)",
            rf"\g<1>{fp}\2",
            orig_text,
            "docs/testing/test-matrix-and-ci-audit.md",
        )
        text = sub_required(
            r"(\|\s*\*\*(?:MATCH|EQUAL|PASS)\*\*\s*\|\s*`)[0-9a-f]{16}(`\s*\|)",
            rf"\g<1>{fp}\2",
            text,
            "docs/testing/test-matrix-and-ci-audit.md",
        )
        text = sub_required(
            r"(under certified release fingerprint )[0-9a-f]{16}",
            rf"\g<1>{fp}",
            text,
            "docs/testing/test-matrix-and-ci-audit.md",
        )
        text = sub_required(
            r'(S_Chr1\["harness/scale_bench\.sh \(Chr1: )[0-9]+\.[0-9]+x speedup, [0-9]+\.[0-9]+x RSS(\)"\])',
            rf"\g<1>{s8:.2f}x speedup, {rss_ratio:.2f}x RSS\2",
            text,
            "docs/testing/test-matrix-and-ci-audit.md",
        )
        text = sub_required(
            r"(\|\s*\*\*Chr1 Scale Benchmark\*\*\s*\|\s*\[`scale\.json`\]\([^)]+\)\s*\|\s*Chromosome 1 Full Scaling\s*\|\s*\$S_8 = )[0-9]+\.[0-9]+(\\times\$, RSS \$)[0-9]+\.[0-9]+(\\times\$)",
            rf"\g<1>{s8:.2f}\g<2>{rss_ratio:.2f}\3",
            text,
            "docs/testing/test-matrix-and-ci-audit.md",
        )
        text = sub_required(
            r"(achieved \*\*)[0-9]+\.[0-9]+×(\*\* \(8 threads vs 1 thread: `)[0-9]+\.[0-9]+s(` vs `)[0-9]+\.[0-9]+s(` 3-run median)",
            rf"\g<1>{s8:.2f}×\g<2>{th8_s:.2f}s\g<3>{th1_s:.2f}s\4",
            text,
            "docs/testing/test-matrix-and-ci-audit.md",
        )
        text = sub_required(
            r"(achieved \*\*)[0-9]+\.[0-9]+×(\*\* \(249 Mbp vs 10 Mbp: `)[0-9]+\.[0-9]+ GiB(` vs `)[0-9]+\.[0-9]+ GiB(` 3-run median)",
            rf"\g<1>{rss_ratio:.2f}×\g<2>{chr1_rss_gib:.2f} GiB\g<3>{span10_rss_gib:.2f} GiB\4",
            text,
            "docs/testing/test-matrix-and-ci-audit.md",
        )
        if text != orig_text:
            if check:
                mismatches.append(str(matrix_path.relative_to(repo_root)))
            else:
                matrix_path.write_text(text, encoding="utf-8")

    # 4. Update benchmarks/README.md
    bench_readme = repo_root / "benchmarks" / "README.md"
    if bench_readme.is_file():
        orig_text = bench_readme.read_text(encoding="utf-8")
        text = sub_required(
            r"(certified release engine fingerprint `)[0-9a-f]{16}(`)",
            rf"\g<1>{fp}\2",
            orig_text,
            "benchmarks/README.md",
        )
        if text != orig_text:
            if check:
                mismatches.append(str(bench_readme.relative_to(repo_root)))
            else:
                bench_readme.write_text(text, encoding="utf-8")

    # 5. Update active docs/release/v<current_version>-pr.md
    cargo_toml = (repo_root / "Cargo.toml").read_text(encoding="utf-8")
    ver_m = re.search(
        r'^\[workspace\.package\]\s*\nversion\s*=\s*"([^"]+)"',
        cargo_toml,
        re.MULTILINE,
    )
    if ver_m:
        ver = ver_m.group(1)
        pr_doc = repo_root / "docs" / "release" / f"v{ver}-pr.md"
        if pr_doc.is_file():
            pr_label = f"docs/release/v{ver}-pr.md"
            orig_text = pr_doc.read_text(encoding="utf-8")
            text = sub_required(
                r"(\*\*Release Fingerprint:\*\*\s*`)[0-9a-f]{16}(`\s*\(`perf_fingerprint`\s*`)[0-9a-f]{16}(`\))",
                rf"\g<1>{fp}\g<2>{perf_fp}\3",
                orig_text,
                pr_label,
            )
            text = sub_required(
                r"(\*\*Release Recertification Receipt \(`)[0-9a-f]{16}(`\):\*\*)",
                rf"\g<1>{fp}\2",
                text,
                pr_label,
            )
            text = sub_required(
                r"(under certified engine fingerprint `)[0-9a-f]{16}(`\s*\(`perf_fingerprint`\s*`)[0-9a-f]{16}(`\):)",
                rf"\g<1>{fp}\g<2>{perf_fp}\3",
                text,
                pr_label,
            )
            text = sub_required(
                r"^(fingerprint )[0-9a-f]{16}$",
                rf"\g<1>{fp}",
                text,
                pr_label,
                flags=re.MULTILINE,
            )
            if text != orig_text:
                if check:
                    mismatches.append(str(pr_doc.relative_to(repo_root)))
                else:
                    pr_doc.write_text(text, encoding="utf-8")

    # 6. Update .agents/skills/vardictrust-release/references/version-surface-map.md
    surface_map = (
        repo_root
        / ".agents"
        / "skills"
        / "vardictrust-release"
        / "references"
        / "version-surface-map.md"
    )
    if surface_map.is_file():
        orig_text = surface_map.read_text(encoding="utf-8")
        text = sub_required(
            r"(\|\s*1[256]\s*\|[^\n]*?`)[0-9a-f]{16}(`)",
            rf"\g<1>{fp}\2",
            orig_text,
            ".agents/skills/vardictrust-release/references/version-surface-map.md",
        )
        text = sub_required(
            r"(\|\s*12\s*\|\s*`DIVERGENCES\.md`\s*\|[^\n]*?`)[0-9]+\.[0-9]+x speedup, [0-9]+\.[0-9]+x flat RSS(`)",
            rf"\g<1>{s8:.2f}x speedup, {rss_ratio:.2f}x flat RSS\2",
            text,
            ".agents/skills/vardictrust-release/references/version-surface-map.md",
        )
        if text != orig_text:
            if check:
                mismatches.append(str(surface_map.relative_to(repo_root)))
            else:
                surface_map.write_text(text, encoding="utf-8")

    if pattern_errors:
        for err in pattern_errors:
            print(err, file=sys.stderr)
        return 1

    if check:
        if mismatches:
            print(
                f"ERROR: documentation surfaces out of sync with benchmarks/evidence/*.json: {', '.join(mismatches)}",
                file=sys.stderr,
            )
            return 1
        print(
            f"Evidence documentation surfaces in sync: fingerprint={fp}, perf_fingerprint={perf_fp} ({sha_rows_verified} SHA-256 rows verified)."
        )
        return 0

    print(
        f"Synced evidence documentation surfaces: fingerprint={fp}, perf_fingerprint={perf_fp} ({sha_rows_verified} SHA-256 rows updated)."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Synchronize documentation fingerprints and SHA-256 evidence tables from benchmarks/evidence/*.json."
    )
    parser.add_argument(
        "--repo-root",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent.parent,
        help="Path to VarDictRust repository root",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check whether documentation surfaces are in sync without writing changes (exits 1 if out of sync)",
    )
    args = parser.parse_args()
    return sync_docs(args.repo_root, check=args.check)


if __name__ == "__main__":
    sys.exit(main())
